// Build the balance presets from research/*.json:
//   src/balance/presets.js  - loaded by the balance page
//   README.md               - the table between the PRESETS markers
// Run by build.sh; edit the JSON files, not the generated output.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const dir = path.join(root, "research");
const order = ["manual.json", "na.json", "apac.json", "eu.json"];
const presets = order
  .filter((f) => fs.existsSync(path.join(dir, f)))
  .flatMap((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")))
  .map((p) => {
    const q = p.method === "sms" ? { to: p.to, text: p.text, ...(p.replyFrom && { replyFrom: p.replyFrom }) } : { code: p.code };
    return {
      country: p.country, carrier: p.carrier, match: p.match, plmn: p.plmn, ...q,
      note: p.note || "", source: p.source || "", confidence: p.confidence, tested: p.tested ?? null,
      // "official": the carrier's own page says the text is free. "observed": a real SIM sent it with no
      // charge showing up. Scheduled queries require one of the two.
      free: p.free || null,
    };
  });

// The same carrier + method twice would show two identical buttons; keep the first.
const seen = new Set();
const unique = presets.filter((p) => {
  const k = `${p.plmn}|${p.code || p.to + ":" + p.text}`;
  return seen.has(k) ? false : seen.add(k);
});

fs.writeFileSync(path.join(root, "src/balance/presets.js"),
  "// Generated by tools/gen-presets.js from research/*.json. Do not edit by hand.\n" +
  "window.BALANCE_PRESETS = " + JSON.stringify(unique, null, 1) + ";\n");

const status = (p) => p.tested === true ? "已实测可用" : p.tested === false ? "实测不可用（见备注）" : "未经验证";
const how = (p) => p.code ? `USSD \`${p.code}\`` : `短信 \`${p.text}\` → ${p.to}${p.replyFrom ? `（回复来自 ${p.replyFrom}）` : ""}`;
const table = [
  "| 国家/地区 | 运营商 | 方式 | 状态 | 定期查询 | 来源 | 备注 |",
  "|---|---|---|---|---|---|---|",
  ...unique.map((p) => `| ${p.country} | ${p.carrier} | ${how(p)} | ${status(p)} | ${p.free === "official" ? "可以（官方写明免费）" : p.free === "observed" ? "可以（用户实测未扣费）" : "不提供"} | [${p.confidence === "official" ? "官方" : "第三方"}](${p.source.replace(/ /g, "%20")}) | ${p.note.replace(/\|/g, "/")} |`),
].join("\n");

const readme = path.join(root, "README.md");
const text = fs.readFileSync(readme, "utf8");
const re = /<!-- PRESETS:BEGIN -->[\s\S]*<!-- PRESETS:END -->/;
if (!re.test(text)) throw new Error("README.md is missing the PRESETS markers");
fs.writeFileSync(readme, text.replace(re, `<!-- PRESETS:BEGIN -->\n${table}\n<!-- PRESETS:END -->`));
console.log(`${unique.length} presets`);
